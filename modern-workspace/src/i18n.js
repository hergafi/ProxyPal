const dictionaries = { ar, en, fr }

export function translator(locale) {
  const table = dictionaries[locale] || dictionaries.ar
  return (key, vars) => {
    let value = table[key] ?? dictionaries.en[key] ?? key
    if (vars) for (const [name, replacement] of Object.entries(vars)) value = value.split(`{${name}}`).join(String(replacement))
    return value
  }
}

export function localeInfo(locale) {
  return locales[locale] || locales.ar
}
